%% Постоянные
m = 2;
k = 17;

% Палитра
maroon     = [0.2078, 0.3608, 0.4902] % вещественная часть
red        = [0.7529, 0.4235, 0.5176] % мнимая часть
cream      = [0.8000, 0.8000, 0.8000] % серая сетка
background = [1.0000, 1.0000, 1.0000]

% –––––

%% Метод Ньютона

% Все лекции.pdf, «Метод Ньютона», страницы PDF 33-34.
% sem2309_1440.m и sem2309_1620.m, раздел «Метод Ньютона».
%
% P(z) = z^3 + 2iz^2 - 17z + 1.
% P'(z) = 3z^2 + 4iz - 17.
% z_{n+1} = z_n - P(z_n) / P'(z_n).

% Зададим многочлен и его производную для вычислений по формуле Ньютона.
f = @(z) z.^3 + 1i*m*z.^2 - k*z + 1;
df = @(z) 3*z.^2 + 2*1i*m*z - k;

% Выберем начальные приближения для нашего многочлена.
% Сначала рассмотрим уравнение без постоянного слагаемого:
% z(z^2 + 2iz - 17) = 0.
% Получаем z = 0 или (z + i)^2 = 16.
% Отсюда z = 0, z = -4-i, z = 4-i.
% Эти числа уточним методом Ньютона для исходного многочлена.
zStart = [-4-1i 0 4-1i];
zRoots = zeros(1, 3);

% Зададим точность проверки и ограничим число повторений тридцатью шагами.
tol_f = 1e-12;
tol_z = 1e-15;
maxIter = 30;

% –––––

% Для каждого начального числа отдельно найдём приближённый корень.
for j = 1:3
    z = zStart(j);

    for n = 1:maxIter
        % Подставим текущее значение в формулу и получим следующее приближение.
        zNew = z - f(z) / df(z);

        % Остановимся, когда значение многочлена близко к нулю,
        % а новое приближение почти не отличается от предыдущего.
        if abs(f(zNew)) < tol_f && abs(zNew - z) < tol_z
            z = zNew;
            break;
        end

        z = zNew;
    end

    % Сохраним найденное значение и выведем результат проверки подстановкой.
    zRoots(j) = z;

    fprintf('z%d = %.12f %+.12fi\n', j, real(z), imag(z));
    fprintf('|P(z%d)| = %.3e\n', j, abs(f(z)));
    fprintf('Количество итераций: %d\n\n', n);
end

% –––––

%% Комплексный многочлен
% Полученные корни расположены примерно в точках:
% -4.0291 - 0.9928i; 0.0588 + 0.0004i; 3.9703 - 1.0076i.
% Зададим координаты точек с шагом 0.01 по обеим осям.
x = linspace(-5, 5, 1001);
y = linspace(-3, 3, 601);

% Из выбранных координат составим прямоугольную сетку.
[X, Y] = meshgrid(x, y);

% Каждой точке сетки поставим в соответствие комплексное число.
Z = X + 1i * Y;

% Вычислим значение многочлена в каждой точке сетки.
P = Z.^3 + 1i*m*Z.^2 - k*Z + 1;

% real(P) даёт вещественную часть, imag(P) даёт мнимую часть.
% Комплексные числа.pdf, «Комплексные числа», страница PDF 1.
%
% На изолинии значение соответствующей части постоянно.
% Выберем уровни для нашего рисунка.
levels = [-60 -30 -15 0 15 30 60];

% –––––

%% Изолинии вещественной части
figure(1);

% Построим линии, на которых вещественная часть принимает выбранные значения.
contour(X, Y, real(P), levels, 'LineColor', maroon, 'LineWidth', 1.5);

grid on;

xlabel('Re z');
ylabel('Im z');

% Зададим одинаковый масштаб по осям и выбранные границы рисунка.
axis equal;
axis([-5 5 -3 3]);

legend('Re P(z) = c', 'TextColor', 'black');

title('Изолинии вещественной части многочлена');

% Оставим белый фон и серую сетку. Подписи осей сделаем чёрными.
set(gcf, 'Color', background);
set(gca, 'Color', background, 'GridColor', cream, ...
    'GridAlpha', 1, 'XColor', 'black', 'YColor', 'black');

% –––––

%% Изолинии мнимой части
figure(2);

% Аналогично построим изолинии мнимой части, используя пунктирные линии.
contour(X, Y, imag(P), levels, 'LineColor', red, ...
    'LineStyle', '--', 'LineWidth', 1.5);

grid on;

xlabel('Re z');
ylabel('Im z');

axis equal;
axis([-5 5 -3 3]);

legend('Im P(z) = c', 'TextColor', 'black');

title('Изолинии мнимой части многочлена');

set(gcf, 'Color', background);
set(gca, 'Color', background, 'GridColor', cream, ...
    'GridAlpha', 1, 'XColor', 'black', 'YColor', 'black');

% –––––

%% Нулевые изолинии
% В корне одновременно Re P(z) = 0 и Im P(z) = 0.
% Построим обе нулевые изолинии на одном рисунке.
% Их пересечения соответствуют корням многочлена.
figure(3);

contour(X, Y, real(P), [0 0], 'LineColor', maroon, 'LineWidth', 2);

% Сохраним первую линию на рисунке и добавим к ней вторую.
hold on;

contour(X, Y, imag(P), [0 0], 'LineColor', red, ...
    'LineStyle', '--', 'LineWidth', 2);

% Отметим найденные корни кружками в точках пересечения нулевых изолиний.
plot(real(zRoots), imag(zRoots), 'ko', 'MarkerSize', 6);

axis equal;
axis([-5 5 -3 3]);

grid on;

xlabel('Re z');
ylabel('Im z');

legend('Re P(z) = 0', 'Im P(z) = 0', 'Корни P(z)', 'TextColor', 'black');

title('Нулевые изолинии P(z) = z^3 + 2iz^2 - 17z + 1');

set(gcf, 'Color', background);
set(gca, 'Color', background, 'GridColor', cream, ...
    'GridAlpha', 1, 'XColor', 'black', 'YColor', 'black');

hold off;
