%% Задача 1.1. Графики комплекснозначных функций
% Муравьёв Герман


set(0, 'DefaultFigureVisible', 'on');

%% Постоянные
m = 2;
k = 17;

%% Палитра
maroon = [0.5020, 0,      0.1255]; % вещественная часть
red    = [0.8314, 0.3137, 0.3765]; % мнимая часть
white  = [1.0000, 1.0000, 1.0000]; % фон

% –––––

%% Записываем исследуемые функции
% Требуется исследовать две комплекснозначные функции вещественной переменной x, запишем:
% f(x) = exp((m + k*i)x).
% g(x) = cos((m + k*i)x).
%
% Каждая комплекснозначная функция имеет вещественную и мнимую части.
% Если h(x) = u(x) + i*v(x), тогда запишем:
% f(x) = Re(f(x)) + i*Im(f(x))
% g(x) = Re(g(x)) + i*Im(g(x)),
%
% где любая Re(h(x)) является u(x), также любая Im(h(x)) ялвяется v(x). Таким образом
% имеем 4 конечные функции для исследования:
% Re(f(x)), Im(f(x)), Re(g(x)), Im(g(x)).

% –––––

%% Находим вещественную и мнимую части комплексной экспоненты
% Чтобы построить требуемые графики Re(f(x)) и Im(f(x)), представим
% комплексную функцию f(x) в виде u(x) + i*v(x). Тогда выражение без i
% будет вещественной частью, а коэффициент при i – мнимой.
%
% Рассмотрим функцию:
% f(x) = exp((m + k*i)x).
%
% Раскроем скобки, тем самым разделив вещественную и мнимую части показателя:
% (m + k*i)x = m*x + i*k*x.
%
% Используем свойство exp(a + b) = exp(a)*exp(b) и рассмотрим функцию:
% f(x) = exp(m*x)*exp(i*k*x).
%
% Вторым множителем является exp(ikx), чтобы представить его
% в виде вещественной и мнимой частей, то применяем формулу Эйлера:
% exp(i*phi) = cos(phi) + i*sin(phi).
%
% В нашем случае phi = k*x, поэтому имеем:
% exp(i*k*x) = cos(k*x) + i*sin(k*x).
%
% Далее подставим exp(i*k*x) в исходную функцию и раскроем скобки:
% f(x) = exp(m*x) * (cos(k*x) + i*sin(k*x)),
% f(x) = exp(m*x)*cos(k*x) + i*exp(m*x)*sin(k*x).
%
% Сравниваем полученное выражение с формой f(x) = u(x) + i*v(x).
% Слагаемое без i является вещественной частью, а коэффициент при i —
% мнимой частью. Поэтому:
% Re(f(x)) = exp(m*x)*cos(k*x).
% Im(f(x)) = exp(m*x)*sin(k*x).

% –––––

%% Находим вещественную и мнимую части комплексного косинуса
% Чтобы построить требуемые графики Re(g(x)) и Im(g(x)), представим
% комплексную функцию g(x) в виде u(x) + i*v(x). Тогда выражение без i
% будет вещественной частью, а коэффициент при i — мнимой частью.
%
% Рассмотрим функцию:
% g(x) = cos((m + ki)x).
%
% Чтобы привести комплексный косинус к виду u(x) + i*v(x), выразим его
% через комплексные экспоненты. Эта формула следует из формулы Эйлера,
% представим в виде системы:
% exp(i*z) = cos(z) + i*sin(z),
% exp(-i*z) = cos(z) - i*sin(z).
%
% Складывая эти равенства, получаем:
% exp(i*z) + exp(-i*z) = 2*cos(z).
%
% Следовательно:
% cos(z) = (exp(iz) + exp(-iz))/2.
%
% Везвращаемся к исследуемой функции:
% g(x) = cos((m + k*i)x).
%
% Введем переменную (обозначим): z = (m + k*i)x.
% Тогда
% g(x) = cos(z) = (exp(i*z) + exp(-i*z))/2.
%
% Для дальнейшего преобразования необходимо отдельно вычислить показатели
% двух экспонент: i*z и -i*z.
%
% Подставляем z = (m + k*i)x в выражение i*z:
% i*z = i*(m + k*i)x.
%
% Раскрываем скобки:
% i*z = (i*m + i*k*i)x.
%
% Так как i*i = i^2 = -1 (мнимая единица – основа комплексных чисел), получаем:
% i*z = i*(m + k*i)*x = imx + i^2*kx = imx - kx = -kx + imx.
%
% Аналогично вычисляем -i*z:
% -iz= -i*(m + k*i)*x = -imx - i^2*kx = -imx + kx = kx - imx.
%
% Теперь подставляем найденные показатели в экспоненты:
% exp(iz)  = exp(-kx + imx),
% exp(-iz) = exp(kx - imx).
%
% Используем свойство exp(a + b) = exp(a)*exp(b):
% exp(iz)  = exp(-kx) * exp(imx),
% exp(-iz) = exp(kx) * exp(-imx).
%
% Множители exp(-kx) и exp(kx) являются вещественными. Чтобы раскрыть
% оставшиеся комплексные экспоненты, применяем формулу Эйлера.
% exp(i*phi) = cos(phi) + i*sin(phi).
%
% При phi = mx:
% exp(i*mx) = cos(mx) + i*sin(mx).
%
% При phi = -mx, учитывая чётность косинуса и нечётность синуса:
% exp(-i*mx) = cos(mx) - i*sin(mx).
%
% Подставляем эти выражения в ранее полученные формулы:
% exp(iz)  = exp(-kx) * (cos(mx) + i*sin(mx)).
% exp(-iz) = exp(kx) * (cos(mx) - i*sin(mx)).


%% Завершаем преобразование комплексного косинуса
% Ранее мы получили формулу:
% cos(z) = (exp(iz) + exp(-iz))/2.
%
% Подставляем в неё найденные выражения exp(iz) и exp(-iz):
% g(x) = (exp(-kx)*(cos(mx) + i*sin(mx)) + exp(kx)*(cos(mx) - i*sin(mx)))/2.
%
% Раскрываем скобки:
% g(x) = (exp(-kx)*cos(mx) + i*exp(-kx)*sin(mx) + exp(kx)*cos(mx) - i*exp(kx)*sin(mx))/2.
%
% Собираем отдельно слагаемые без i:
% cos(mx) * (exp(kx) + exp(-kx))/2.
%
% Собираем отдельно слагаемые, содержащие i:
% i*sin(mx) * (exp(-kx) - exp(kx))/2.
%
% Выносим знак минус из разности, используя тождество A - B = -(B - A):
% i*sin(mx) * (exp(-kx) - exp(kx))/2 = -i*sin(mx)*(exp(kx) - exp(-kx))/2.
%
% Поэтому:
% g(x) = cos(mx) * (exp(kx) + exp(-kx))/2 - i*sin(mx) * (exp(kx) - exp(-kx))/2.
%
% В полученном выражении присутствуют сумма и разность экспонент:
% (exp(kx) + exp(-kx))/2,
% (exp(kx) - exp(-kx))/2.
%
% Данные выражения являются гиперболическим косинусом
% и гиперболическим синусом по их определению:
% cosh(t) = (exp(t) + exp(-t))/2.
% sinh(t) = (exp(t) - exp(-t))/2.
%
% В нашем случае t = kx, поэтому обозначим t как kx:
% cosh(kx) = (exp(kx) + exp(-kx))/2.
% sinh(kx) = (exp(kx) - exp(-kx))/2.
%
% Используем эти обозначения, чтобы записать результат короче:
% g(x) = cos(mx)*cosh(kx) - i*sin(mx)*sinh(kx).
%
% Получили выражение вида u(x) + i*v(x). Поэтому:
% Re(g(x)) = cos(mx)*cosh(kx).
% Im(g(x)) = -sin(mx)*sinh(kx).


%% Подставляем постоянные m и k
%
% Re(f(x)) = exp(2x) * cos(17x).
% Im(f(x)) = exp(2x) * sin(17x).
% Re(g(x)) = cos(2x) * cosh(17x).
% Im(g(x)) = -sin(2x) * sinh(17x).

% –––––

%% Выбираем отрезок для комплексной экспоненты
% Ранее мы получили:
% Re(f(x)) = exp(2*x)*cos(17*x).
% Im(f(x)) = exp(2*x)*sin(17*x).
%
% Функции cos(17x) и sin(17x) отвечают за колебания. Так найдём их период.
% Синус и косинус повторяют значения, когда их аргумент увеличивается
% на полный оборот 2pi. Поэтому период T удовлетворяет равенству:
% 17T = 2pi.
%
% Следовательно:
% T = 2pi/17 = 0.37
%
% Так как T у нас небольшой (0.37), предпочитаю выбрать небольшой отрезок: [-1, 1].
% Его длина равна 2. Количество периодов на этом отрезке равно:
% 2/T = 2/(2pi/17) = 17/pi = 5.41
%
% Следовательно, на отрезке [-1, 1] видно больше пяти колебаний.
% Множитель exp(2x) определяет амплитуду колебаний. На концах выбранного
% отрезка он принимает значения:
% exp(-2) = 0.135,
% exp(2) = 7.389.
%
% Поэтому на графике будет видно, что слева амплитуда мала, а при движении
% вправо она увеличивается. Отрезок [-1, 1] показывает как колебания,
% так и изменение их амплитуды.
x_exp = linspace(-1, 1, 4000);


%% Вычисляем комплексную экспоненту
% Для каждого значения x вычисляем исходную комплекснозначную функцию.
% f(x) = exp((m + k*i)x).
f = exp((m + k*1i) .* x_exp);

%% Выделяем части комплексной экспоненты
% Команды real и imag выделяют требуемые вещественную и мнимую части.
% Re(f(x)) = exp(2x) * cos(17x).
% Im(f(x)) = exp(2x) * sin(17x).
f_real = real(f);
f_imag = imag(f);

%% Строим график комплексной экспоненты
% y_1(x) = Re(f(x)) = exp(2x) * cos(17x).
% y_2(x) = Im(f(x)) = exp(2x) * sin(17x).

figure(1);
set(gcf, 'Color', white);
set(gca, 'Color', white);
set(gcf, 'Visible', 'on', 'WindowStyle', 'normal');

plot(x_exp, f_real, ...
    'Color', maroon, ...
    'LineWidth', 1.5);

hold on;

plot(x_exp, f_imag, ...
    'Color', red, ...
    'LineWidth', 1.5);

grid on;
xlabel('x');
ylabel('y');

legend('Re(exp((2 + 17i)x)) = exp(2x)cos(17x)', ...
       'Im(exp((2 + 17i)x)) = exp(2x)sin(17x)', ...
       'Location', 'northwest');

title('Вещественная и мнимая части комплексной экспоненты');

hold off;
drawnow;

%% Выбираем отрезки для комплексного косинуса
% Из полученных формул видно, что cosh(17x) и sinh(17x) быстро растут
% при увеличении |x|. Отрезок [-1, 1] показывает общее поведение и
% ближайшие нули вещественной части. Отрезок [-0.25, 0.25] дополнительно
% показывает поведение функций около нуля.
% cos(2*x) = 0 при x = +/- pi/4.
x_cos = linspace(-1, 1, 5000);
x_zoom = linspace(-0.25, 0.25, 3000);

%% Вычисляем комплексный косинус
% Вычисляем исходную функцию на общем и увеличенном отрезках.
% g(x) = cos((m + k*i)x).
g = cos((m + k*1i) .* x_cos);
g_zoom = cos((m + k*1i) .* x_zoom);

%% Выделяем части комплексного косинуса
% Команды real и imag выделяют требуемые вещественную и мнимую части.
% Re(g(x)) = cos(2*x)*cosh(17*x).
% Im(g(x)) = -sin(2*x)*sinh(17*x).
g_real = real(g);
g_imag = imag(g);
g_real_zoom = real(g_zoom);
g_imag_zoom = imag(g_zoom);

%% Строим общий график комплексного косинуса
% В левой части рисунка показываем поведение функций на отрезке [-1, 1].
% y_1(x) = Re(g(x)) = cos(2*x)*cosh(17*x).
% y_2(x) = Im(g(x)) = -sin(2*x)*sinh(17*x).

figure(2);
set(gcf, 'Color', white);
set(gcf, 'Visible', 'on', 'WindowStyle', 'normal');

subplot(1, 2, 1);
set(gca, 'Color', white);

plot(x_cos, g_real, ...
    'Color', maroon, ...
    'LineWidth', 1.5);

hold on;

plot(x_cos, g_imag, ...
    'Color', red, ...
    'LineWidth', 1.5);

grid on;
xlabel('x');
ylabel('y');

legend('Re(cos((2 + 17i)x))', ...
       'Im(cos((2 + 17i)x))', ...
       'Location', 'south');

title('Общее поведение на [-1, 1]');

hold off;
drawnow;

%% Строим увеличенный график комплексного косинуса
% В правой части рисунка показываем поведение функций около нуля.
% y_1(x) = Re(g(x)) = cos(2*x)*cosh(17*x).
% y_2(x) = Im(g(x)) = -sin(2*x)*sinh(17*x).

subplot(1, 2, 2);
set(gca, 'Color', white);

plot(x_zoom, g_real_zoom, ...
    'Color', maroon, ...
    'LineWidth', 1.5);

hold on;

plot(x_zoom, g_imag_zoom, ...
    'Color', red, ...
    'LineWidth', 1.5);

grid on;
xlabel('x');
ylabel('y');

legend('Re(cos((2 + 17i)x))', ...
       'Im(cos((2 + 17i)x))', ...
       'Location', 'south');

title('Увеличение на [-0.25, 0.25]');

hold off;
drawnow;

%% Вывод
% Получены и построены все 4 требуемые вещественные функции.
% Первый рисунок показывает колебания комплексной экспоненты и изменение
% их амплитуды. Второй рисунок показывает быстрый рост частей комплексного
% косинуса и их поведение около нуля.

% –––––

