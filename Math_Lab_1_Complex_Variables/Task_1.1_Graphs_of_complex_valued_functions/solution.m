%% Постоянные
m = 2;
k = 17;

%% Палитра
maroon     = [0.5020, 0, 0.1255];      % вещественная часть
red        = [0.8314, 0.3137, 0.3765]; % мнимая часть
gray       = [0.4000, 0.4000, 0.4000]; % огибающие
background = [1.0000, 1.0000, 1.0000];

% –––––

%% Выбираем отрезок для комплексной экспоненты
% Вещественная и мнимая части содержат cos(17x) и sin(17x).
% Их период равен T = 2*pi/17 = 0.37.
% На отрезке [-1, 1] помещается 17/pi = 5.41 периода.
% Этого достаточно для того, чтобы увидеть больше пяти колебаний функции.
x_exp = linspace(-1, 1, 4000);

%% Вычисляем комплексную экспоненту
% Подставляем все значения x в исходную функцию
% f(x) = exp((m + ki)x).
f = exp((m + k*1i) .* x_exp);

%% Находим вещественную и мнимую части комплексной экспоненты
% Функция real выделяет вещественную часть комплексного числа.
% Получаем Re(f(x)) = exp(2x)cos(17x).
f_real = real(f);

% Функция imag выделяет мнимую часть комплексного числа.
% Получаем Im(f(x)) = exp(2x)sin(17x).
f_imag = imag(f);

% Множитель exp(2x) определяет наибольший размах колебаний.
% Поэтому дополнительно вычисляем верхнюю и нижнюю огибающие.
upper_envelope = exp(m * x_exp);
lower_envelope = -exp(m * x_exp);

% –––––

%% Строим график комплексной экспоненты
% Создаём первое окно рисунка и задаём белый фон.
figure(1);
set(gcf, 'Color', background);
set(gca, 'Color', background);

% Строим вещественную часть комплексной экспоненты бордовым цветом.
f_real_plot = plot(x_exp, f_real, ...
    'Color', maroon, 'LineWidth', 1.5);

hold on;

% Строим мнимую часть комплексной экспоненты красным цветом.
f_imag_plot = plot(x_exp, f_imag, ...
    'Color', red, 'LineWidth', 1.5);

% Строим верхнюю огибающую y = exp(2x) серой пунктирной линией.
upper_envelope_plot = plot(x_exp, upper_envelope, '--', ...
    'Color', gray, 'LineWidth', 1.0);

% Строим нижнюю огибающую y = -exp(2x) такой же линией.
lower_envelope_plot = plot(x_exp, lower_envelope, '--', ...
    'Color', gray, 'LineWidth', 1.0);

% Обе огибающие имеют одинаковый смысл, поэтому нижнюю линию
% отдельно в легенду не добавляем.
set(lower_envelope_plot, 'HandleVisibility', 'off');

grid on;
xlabel('x');
ylabel('y');

% Ограничиваем горизонтальную ось выбранным отрезком [-1, 1].
xlim([-1 1]);

% Легенда
legend( ...
    [f_real_plot, f_imag_plot, upper_envelope_plot], ...
    'Re(f(x)) = exp(2x)cos(17x)', ...
    'Im(f(x)) = exp(2x)sin(17x)', ...
    'Огибающие y = +/- exp(2x)', ...
    'Location', 'northwest');

title('Вещественная и мнимая части комплексной экспоненты');

hold off;

% –––––

%% Выбираем отрезки для комплексного косинуса
% Множители cosh(17x) и sinh(17x) быстро растут при увеличении |x|.
% Сначала выбираем отрезок [-1, 1], чтобы увидеть общий характер роста.
x_cos = linspace(-1, 1, 5000);

% На общем графике поведение около нуля плохо различимо.
% Поэтому дополнительно выбираем увеличенный отрезок [-0.25, 0.25].
x_zoom = linspace(-0.25, 0.25, 3000);

%% Вычисляем комплексный косинус
% Подставляем значения общего отрезка в исходную функцию
% g(x) = cos((m + ki)x).
g = cos((m + k*1i) .* x_cos);

% Отдельно вычисляем эту функцию на увеличенном отрезке около нуля.
g_zoom = cos((m + k*1i) .* x_zoom);

%% Находим части комплексного косинуса на общем отрезке
% Выделяем вещественную часть Re(g(x)) = cos(2x)cosh(17x).
g_real = real(g);

% Выделяем мнимую часть Im(g(x)) = -sin(2x)sinh(17x).
g_imag = imag(g);

%% Находим части комплексного косинуса около нуля
% Выделяем вещественную часть на увеличенном отрезке.
g_real_zoom = real(g_zoom);

% Выделяем мнимую часть на увеличенном отрезке.
g_imag_zoom = imag(g_zoom);

% –––––

%% Строим графики комплексного косинуса
figure(2);
set(gcf, 'Color', background);

%% Строим общий график комплексного косинуса
% Разделяем окно на одну строку и два столбца.
% В левой части выбираем первый график.
subplot(1, 2, 1);
set(gca, 'Color', background);

% Строим вещественную часть на отрезке [-1, 1] бордовым цветом.
g_real_plot = plot(x_cos, g_real, ...
    'Color', maroon, 'LineWidth', 1.5);

hold on;

% Строим мнимую часть на отрезке [-1, 1] красным цветом.
g_imag_plot = plot(x_cos, g_imag, ...
    'Color', red, 'LineWidth', 1.5);

grid on;
xlabel('x');
ylabel('y');

%% Легенда
legend( ...
    [g_real_plot, g_imag_plot], ...
    'Re(g(x)) = cos(2x)cosh(17x)', ...
    'Im(g(x)) = -sin(2x)sinh(17x)', ...
    'Location', 'south');

title('Общее поведение на [-1, 1]');

hold off;

%% Строим увеличенный график комплексного косинуса
% В правой части окна выбираем второй график.
subplot(1, 2, 2);
set(gca, 'Color', background);

% Строим вещественную часть около нуля бордовым цветом.
g_real_zoom_plot = plot(x_zoom, g_real_zoom, ...
    'Color', maroon, 'LineWidth', 1.5);

% Сохраняем первый график и добавляем мнимую часть в те же оси.
hold on;

% Строим мнимую часть около нуля красным цветом.
g_imag_zoom_plot = plot(x_zoom, g_imag_zoom, ...
    'Color', red, 'LineWidth', 1.5);

% Включаем сетку, подписываем оси и добавляем легенду.
grid on;
xlabel('x');
ylabel('y');

legend( ...
    [g_real_zoom_plot, g_imag_zoom_plot], ...
    'Re(g(x)) = cos(2x)cosh(17x)', ...
    'Im(g(x)) = -sin(2x)sinh(17x)', ...
    'Location', 'south');

title('Имеем около нуля на [-0.25, 0.25]');

hold off;

