%% Постоянные
m = 2;
k = 17;

%% Палитра
dark       = [0.0039, 0.0275, 0.2118]; % граница первой области, ось и отмеченные точки
navy       = [0.0510, 0.1098, 0.2588]; % граница второй области, сетка и рамка легенды
blue       = [0.1333, 0.2235, 0.4353]; % пересечение двух областей
background = [1.0000, 1.0000, 1.0000];

%% Прямоугольник построения
% Вторая область |z - 17i| < 2 является кругом радиуса 2
% с центром в точке (0, 17). Поэтому она расположена в пределах:
% -2 < a < 2 и 15 < b < 19.
%
% Выбираем прямоугольник: -4 <= a <= 4 и 13 <= b <= 21.
% Поменяем значения, так как дополнительный отступ
% позволяет увидеть границы обеих областей и их общую точку (0, 15).
a = linspace(-4, 4, 400);
b = linspace(13, 21, 400);

% Создаём двумерную сетку точек (a, b) на выбранном прямоугольнике.
% Матрица A содержит вещественные координаты, а матрица B – мнимые.
[A, B] = meshgrid(a, b);

% Каждой точке (a, b) комплексной плоскости соответствует комплексное число
% z = a + bi. Поэтому составляем матрицу комплексных чисел Z.
Z = A + 1i * B;

%% Области и логические условия
% Первая область имеет вид: |z + mi| > k.
% Выражение |z + mi| задаёт расстояние от точки z до точки -mi,
% которой соответствует точка (0, -m). Условие > k выбирает точки,
% расположенные снаружи окружности радиуса k, так как строго больше.
% При m = 2 и k = 17 получаем условие |z + 2i| > 17.
condition1 = abs(Z + m*1i) > k;

% Вторая область имеет вид |z - ki| < m.
% Выражение |z - ki| задаёт расстояние от точки z до точки ki,
% которой соответствует точка (0, k). Условие < m выбирает точки,
% расположенные внутри окружности радиуса m, так как строго меньше.
% При k = 17 и m = 2 получаем условие |z - 17i| < 2.
condition2 = abs(Z - k*1i) < m;

% Значение region равно true только для точек, принадлежащих
% одновременно первой и второй областям.
region = condition1 & condition2;

%% Границы областей
% Граница первой области получается при равенстве |z + mi| = k,
% а граница второй области – при равенстве |z - ki| = m.
% Поэтому отдельно вычисляем значения обоих модулей во всех точках
% сетки. Эти матрицы используются далее для построения линий уровня.
F1 = abs(Z + m*1i);
F2 = abs(Z - k*1i);

%% Пересечение областей на комплексной плоскости
% Создаём окно рисунка. Точки пересечения выбираются логической
% маской region и изображаются синими маркерами.
figure(1);

regionPlot = plot(A(region), B(region), '.', ...
    'Color', blue, 'MarkerSize', 8);

hold on;

% Строим линию уровня F1 = k. Она соответствует границе
% |z + 2i| = 17. Пунктир показывает, что при строгом знаке >
% сама граница не входит в первую область.
[~, firstBoundary] = contour(A, B, F1, [k k], '--', ...
    'LineColor', dark, 'LineWidth', 2);

% Строим линию уровня F2 = m. Она соответствует границе
% |z - 17i| = 2. Пунктир показывает, что при строгом знаке <
% сама граница не входит во вторую область.
[~, secondBoundary] = contour(A, B, F2, [m m], '--', ...
    'LineColor', navy, 'LineWidth', 2);

% Центр второй окружности соответствует комплексному числу ki.
% При k = 17 его координаты равны (0, 17).
centerPlot = plot(0, k, 'x', ...
    'Color', dark, 'MarkerSize', 9, 'LineWidth', 2);

% Границы окружностей имеют общую точку (0, k - m).
% При k = 17 и m = 2 получаем точку (0, 15).
% Пустой маркер показывает, что эта точка не входит в пересечение,
% поскольку в исходных условиях используются строгие неравенства.
commonPointPlot = plot(0, k-m, 'o', ...
    'Color', dark, 'MarkerFaceColor', background, ...
    'MarkerSize', 7, 'LineWidth', 2);

% Проводим мнимую ось a = 0 в пределах выбранного прямоугольника.
imaginaryAxis = plot([0 0], [13 21], ...
    'Color', dark, 'LineWidth', 0.8);

% Не добавляем вспомогательную мнимую ось в легенду.
% Функция set используется и в MATLAB, и в Octave.
set(imaginaryAxis, 'HandleVisibility', 'off');

% Включаем координатную сетку.
grid on;

% Одинаковый масштаб по двум осям сохраняет форму окружностей.
% Затем устанавливаем выбранные границы прямоугольника построения.
axis equal;
axis([-4 4 13 21]);

% Горизонтальная ось соответствует вещественной части числа z,
% вертикальная ось – его мнимой части.
xlabel('Re z');
ylabel('Im z');

title('Пересечение областей на комплексной плоскости');

% –––––

%% Легенда
legend( ...
    [regionPlot, firstBoundary, secondBoundary, centerPlot, commonPointPlot], ...
    'Пересечение: |z+2i|>17 и |z-17i|<2', ...
    'Граница |z+2i|=17 (не входит)', ...
    'Граница |z-17i|=2 (не входит)', ...
    'Центр второй окружности (0,17)', ...
    'Общая точка границ (0,15) (не входит)', ...
    'Location', 'southoutside');

set(gcf, 'Color', background);
set(gca, ...
    'Color', background, ...
    'GridColor', navy, ...
    'GridAlpha', 0.18);

hold off;

